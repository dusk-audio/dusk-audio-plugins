#!/usr/bin/env python3
"""Generate core/MinBlepTable.hpp: the oscillators' minimum-phase band-limited step (#303).

  gen_minblep.py           write the header
  gen_minblep.py --check   compare the committed header with a fresh generation (to float precision)

The kernel is a windowed sinc (cutoff 0.45 of the oscillator's own rate, Kaiser
beta 8, 8 zero crossings each side, so 16 samples long), turned minimum phase
by the real cepstrum (so all of it lies after the step and nothing has to be
delayed to apply it), and integrated into a step. The table holds the residual
of a unit step, step(x) - 1, at 128 points per sample over x = 0 .. 16 samples
after the step; the last point is 0. Its group delay at DC is written too: the
oscillators' steps land that much later on average than the step itself, which
the latency pad gives back (MultiSynthDSP, CONSTANT LATENCY).
"""
import os
import re
import sys

import numpy as np

ZERO_CROSSINGS = 8
POINTS_PER_SAMPLE = 128
CUTOFF = 0.45
KAISER_BETA = 8.0
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "core", "MinBlepTable.hpp")


def generate():
    n = 2 * ZERO_CROSSINGS * POINTS_PER_SAMPLE + 1
    x = (np.arange(n) - ZERO_CROSSINGS * POINTS_PER_SAMPLE) / POINTS_PER_SAMPLE
    h = 2.0 * CUTOFF * np.sinc(2.0 * CUTOFF * x) * np.kaiser(n, KAISER_BETA)
    size = 1 << int(np.ceil(np.log2(n * 32)))
    cep = np.fft.ifft(np.log(np.maximum(np.abs(np.fft.fft(h, size)), 1e-12))).real
    fold = np.zeros(size)
    fold[0] = 1.0
    fold[1:size // 2] = 2.0
    fold[size // 2] = 1.0
    hmin = np.fft.ifft(np.exp(np.fft.fft(cep * fold))).real[:n]
    step = np.cumsum(hmin)
    step /= step[-1]
    taps = 2 * ZERO_CROSSINGS
    residual = step[:taps * POINTS_PER_SAMPLE + 1] - 1.0
    residual[-1] = 0.0
    delay = float(np.sum(hmin * np.arange(n)) / np.sum(hmin)) / POINTS_PER_SAMPLE
    return residual.astype(np.float32), delay


def literal(v):
    t = "%.9g" % v
    return (t if any(c in t for c in ".e") else t + ".0") + "f"


def render(residual, delay):
    rows = ",\n".join("    " + ", ".join(literal(v) for v in residual[i:i + 6]) for i in range(0, len(residual), 6))
    return f"""// Copyright (C) 2026 Dusk Audio - GNU GPL v3.0 or later (see repository LICENSE).
//
// MinBlepTable.hpp - GENERATED by daf-plugin/tools/gen_minblep.py; do not edit.
// Residual of a minimum-phase band-limited unit step (step(x) - 1) at
// {POINTS_PER_SAMPLE} points per sample, x = 0 .. {2 * ZERO_CROSSINGS} samples after the step. Windowed
// sinc, cutoff {CUTOFF} of the sample rate, Kaiser beta {KAISER_BETA:g}, {ZERO_CROSSINGS} zero crossings a side,
// minimum phase by the real cepstrum. See Oscillator.hpp (MINIMUM-PHASE BLEP).

#pragma once

namespace msynth
{{

constexpr int kMinBlepTaps = {2 * ZERO_CROSSINGS};
constexpr int kMinBlepPointsPerSample = {POINTS_PER_SAMPLE};
// Group delay of the kernel at DC, in samples of the oscillator's own rate.
constexpr double kMinBlepDelaySamples = {delay:.6f};

constexpr float kMinBlepResidual[{len(residual)}] = {{
{rows}
}};

}} // namespace msynth
"""


def parse(text):
    body = text.split("kMinBlepResidual")[1].split("{", 1)[1].split("}", 1)[0]
    vals = np.array([float(v.rstrip("f")) for v in re.findall(r"[-0-9.e+]+f", body)])
    delay = float(re.search(r"kMinBlepDelaySamples = ([0-9.]+);", text).group(1))
    return vals, delay


def main():
    residual, delay = generate()
    text = render(residual, delay)
    if "--check" in sys.argv:
        try:
            have = open(OUT).read()
        except OSError as e:
            print(f"gen_minblep --check: cannot read {OUT}: {e}")
            sys.exit(1)
        vals, d = parse(have)
        # Float precision, not bytes: the FFT's last bits may differ between numpy builds.
        ok = len(vals) == len(residual) and np.max(np.abs(vals - residual)) <= 2e-7 and abs(d - delay) <= 1e-5
        print("gen_minblep --check: " + ("OK (%d points, DC delay %.4f samples)" % (len(vals), d) if ok else
              "DRIFT: core/MinBlepTable.hpp does not match gen_minblep.py; re-run it and commit the result"))
        sys.exit(0 if ok else 1)
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote %s: %d points, DC delay %.4f samples" % (os.path.normpath(OUT), len(residual), delay))


if __name__ == "__main__":
    main()
